#!/usr/bin/env python3
"""Generate firmware tables and offline run bundles for the agreed 21 recordings.

No serial port is opened by this tool. Uses only the Python standard library.
"""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "experiments/session_2026-11-16.json"
HEADER = ROOT / "arduino/recording_session/generated_session.h"
COLOURS = "RGB"
MODES = {"legacy": 0, "off": 1, "single": 2, "fixed": 3, "selected": 4, "irregular": 5}
FIELDS = ["phase", "slot", "colour", "omitted", "target_on_us", "target_off_us", "slot_end_us"]


def load_design():
    return json.loads(DESIGN.read_text())


def design_hash(design):
    return hashlib.sha256(json.dumps(design, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def irregular_slots(design, sequence):
    """Stable integer-only PRNG; save the realised table, not just its seed."""
    state = design["irregular"]["seeds"][sequence]

    def draw(n):
        nonlocal state
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        state &= 0xFFFFFFFF
        return state % n

    slots = []
    order = []
    omitted_in_block = 0
    for i in range(design["irregular"]["slots"]):
        if i % 10 == 0:
            omitted_in_block = draw(10)
        if i % 3 == 0:
            order = [0, 1, 2]
            for j in (2, 1):
                k = draw(j + 1)
                order[j], order[k] = order[k], order[j]
        gap_index = draw(len(design["irregular"]["gap_multipliers"]))
        slots.append((order[i % 3], gap_index, i % 10 == omitted_in_block))
    return slots


def cycle_count(design, profile):
    p = design["profiles"][profile]
    cycle = 3 * (p["on_us"] + p["off_us"])
    return max(design["minimum_rgb_cycles"], (design["minimum_measurement_us"] + cycle - 1) // cycle)


def rows_for_run(design, run, selected):
    if run["mode"] == "legacy":
        return []  # Export a self-timed recipe instead of inventing exact edges.
    if run["mode"] in ("selected", "irregular") and selected is None:
        return None
    rows = []
    cursor = 0

    def idle(phase, duration):
        nonlocal cursor
        rows.append([phase, -1, "-", 0, cursor, cursor + duration, cursor + duration])
        cursor += duration

    def pulse(phase, slot, channel, on, gap, omitted=False):
        nonlocal cursor
        rows.append([phase, slot, COLOURS[channel], int(omitted), cursor, cursor + on, cursor + on + gap])
        cursor += on + gap

    idle("pre_dark", design["pre_dark_us"])
    if run["mode"] == "off":
        idle("measurement_dark", design["dark_control_us"])
    else:
        for i, p in enumerate(design["preamble"]):
            pulse("preamble", i, COLOURS.index(p["colour"]), p["on_us"], p["off_us"])
        idle("settle_dark", design["settle_dark_us"])
        mode = run["mode"]
        if mode == "single":
            p = design["profiles"]["S"]
            for i in range(design["single_channel_pulses"]):
                pulse("measurement", i, COLOURS.index(run["colour"]), p["on_us"], p["off_us"])
        elif mode in ("fixed", "selected"):
            profile = run.get("profile", selected)
            p = design["profiles"][profile]
            for i in range(3 * cycle_count(design, profile)):
                pulse("measurement", i, i % 3, p["on_us"], p["off_us"])
        else:
            p = design["profiles"][selected]
            base_gap = max(p["off_us"], design["irregular"]["minimum_base_gap_us"])
            for i, (channel, gap_index, omitted) in enumerate(irregular_slots(design, run["sequence"])):
                pulse("measurement", i, channel, p["on_us"],
                      base_gap * design["irregular"]["gap_multipliers"][gap_index], omitted)
    idle("post_dark", design["post_dark_us"])
    return rows


def csv_text(rows):
    out = io.StringIO(newline="")
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(FIELDS)
    writer.writerows(rows)
    return out.getvalue()


def generated_header(design):
    lines = ["// Generated by tools/prepare_recording_session.py generate. Do not edit.",
             "#pragma once", "#include <stdint.h>", "#ifdef __AVR__", "#include <avr/pgmspace.h>",
             "#else", "#define PROGMEM", "#define pgm_read_byte(p) (*(const uint8_t *)(p))", "#endif",
             'static const char DESIGN_SHA[] = "' + design_hash(design) + '";',
             "enum RunMode { LEGACY, OFF, SINGLE, FIXED, SELECTED, IRREGULAR };",
             "struct RunSpec { char id[5]; uint8_t mode; int8_t parameter; };",
             "struct TimingProfile { uint32_t on_us, off_us; uint16_t cycles; };",
             "struct Marker { uint8_t channel; uint32_t on_us, off_us; };",
             "static const RunSpec RUNS[] PROGMEM = {"]
    for run in design["runs"]:
        parameter = -1
        if run["mode"] == "single":
            parameter = COLOURS.index(run["colour"])
        elif run["mode"] == "fixed":
            parameter = int(run["profile"][1]) - 1
        elif run["mode"] == "irregular":
            parameter = run["sequence"]
        lines.append('  {"%s", %d, %d},' % (run["id"], MODES[run["mode"]], parameter))
    lines += ["};", "static const uint8_t RUN_COUNT = sizeof(RUNS) / sizeof(RUNS[0]);",
              "static const TimingProfile PROFILES[] PROGMEM = {"]
    for profile in ("T1", "T2", "T3"):
        p = design["profiles"][profile]
        lines.append("  {%dUL, %dUL, %d}," % (p["on_us"], p["off_us"], cycle_count(design, profile)))
    lines += ["};", "static const Marker PREAMBLE[] PROGMEM = {"]
    for p in design["preamble"]:
        lines.append("  {%d, %dUL, %dUL}," % (COLOURS.index(p["colour"]), p["on_us"], p["off_us"]))
    lines += ["};", "static const uint8_t PREAMBLE_COUNT = sizeof(PREAMBLE) / sizeof(PREAMBLE[0]);"]
    constants = {"PRE_DARK_US": design["pre_dark_us"], "SETTLE_DARK_US": design["settle_dark_us"],
                 "POST_DARK_US": design["post_dark_us"], "DARK_CONTROL_US": design["dark_control_us"],
                 "SINGLE_ON_US": design["profiles"]["S"]["on_us"],
                 "SINGLE_OFF_US": design["profiles"]["S"]["off_us"],
                 "SINGLE_PULSES": design["single_channel_pulses"],
                 "IRREGULAR_BASE_GAP_US": design["irregular"]["minimum_base_gap_us"],
                 "IRREGULAR_SLOTS": design["irregular"]["slots"],
                 "LEGACY_STARTUP_US": design["legacy_reconstruction"]["startup_dark_us"],
                 "LEGACY_MEASUREMENT_US": design["legacy_reconstruction"]["measurement_min_us"],
                 "LEGACY_RAMP_US": design["legacy_reconstruction"]["ramp_us"],
                 "LEGACY_DARK_US": design["legacy_reconstruction"]["zero_command_us"],
                 "LEGACY_UPDATE_INCREMENT_US": design["legacy_reconstruction"]["next_update_increment_us"]}
    lines += ["static const uint32_t %s = %dUL;" % item for item in constants.items()]
    lines += ["static const uint8_t GAP_MULTIPLIERS[] PROGMEM = {" +
              ", ".join(map(str, design["irregular"]["gap_multipliers"])) + "};",
              "// Packed: channel bits 0-1, gap index bits 2-3, omitted bit 4.",
              "static const uint8_t IRREGULAR_DATA[2][%d] PROGMEM = {" % design["irregular"]["slots"]]
    for sequence in range(2):
        packed = [c | (g << 2) | (int(o) << 4) for c, g, o in irregular_slots(design, sequence)]
        lines.append("  {")
        for i in range(0, len(packed), 20):
            lines.append("    " + ", ".join(map(str, packed[i:i + 20])) + ",")
        lines.append("  },")
    return "\n".join(lines + ["};", ""])


def generate(check=False):
    design = load_design()
    files = {HEADER: generated_header(design)}
    for sequence in range(2):
        out = io.StringIO(newline="")
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(["slot", "colour", "gap_multiplier", "omitted", "seed"])
        for i, (c, g, o) in enumerate(irregular_slots(design, sequence)):
            writer.writerow([i, COLOURS[c], design["irregular"]["gap_multipliers"][g], int(o),
                             design["irregular"]["seeds"][sequence]])
        files[ROOT / ("experiments/irregular_2026-11-16_J%d.csv" % (sequence + 1))] = out.getvalue()
    for path, content in files.items():
        if check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit("Stale generated file: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Generated files verified" if check else "Generated firmware table and both realised J schedules")


def prepare(output, selected):
    generate(check=True)
    design = load_design()
    output.mkdir(parents=True, exist_ok=False)
    (output / "design.json").write_text(json.dumps(design, indent=2) + "\n")
    source_hashes = {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
                     for path in sorted((ROOT / "arduino/recording_session").glob("*")) if path.is_file()}
    (output / "source_hashes.json").write_text(json.dumps(source_hashes, indent=2) + "\n")
    snapshot = output / "firmware_source"
    snapshot.mkdir()
    for path in sorted((ROOT / "arduino/recording_session").glob("*")):
        if path.is_file():
            (snapshot / path.name).write_bytes(path.read_bytes())
    sheet = []
    for run in design["runs"]:
        rows = rows_for_run(design, run, selected)
        needs_selection = run["mode"] in ("selected", "irregular")
        legacy = run["mode"] == "legacy"
        command = "RUN " + run["id"]
        if command and needs_selection:
            command += " " + (selected or "<T1|T2|T3>")
        schedule_file = run["id"] + "_schedule.csv" if rows else None
        if rows:
            (output / schedule_file).write_text(csv_text(rows))
        if legacy:
            schedule_file = run["id"] + "_schedule.json"
            recipe = {"schema_version": 3, "run_id": run["id"],
                      "reference_backup": design["original_firmware"],
                      **design["legacy_reconstruction"]}
            (output / schedule_file).write_text(json.dumps(recipe, indent=2) + "\n")
        planned_total = (design["legacy_reconstruction"]["startup_dark_us"] +
                         design["legacy_reconstruction"]["measurement_min_us"]) if legacy else (rows[-1][-1] if rows else None)
        metadata = {
            "schema_version": 3, "status": "unrecorded", "session_id": design["session_id"],
            **run, "serial_command": command, "design_sha256": design_hash(design),
            "selected_condition": selected if needs_selection else None,
            "command_schedule": schedule_file,
            "planned_total_us": planned_total,
            "planned_total_kind": "minimum_plus_cycle_completion_and_overhead" if legacy else "deadline_targets",
            "time_origin": "firmware run_origin_us after START output is flushed",
            "timing_reference": "self-timed ramp/dark targets; no exact GPIO or optical edge table" if legacy else design["timing_reference"],
            "firmware": {"source_snapshot": "firmware_source", "source_hashes": "source_hashes.json", "compiled_hex_sha256": None,
                         "pin_colour_mapping_verified": None, "polarity_verified": None,
                         "identity": "reconstructed_original_firmware" if legacy else "selectable_digital_firmware",
                         "exact_binary_reproduction": False,
                         "reference_backup": design["original_firmware"] if legacy else None},
            "actual": {"date_time_with_timezone": None, "camera_model": None, "camera_config_file": None,
                       "bias_and_filter_settings": None, "erc_drop_statistics": None,
                       "layout_map_file": None, "target_ids": None, "setup_photo": None,
                       "illumination_geometry_and_drive": None, "ambient_and_box_opening_state": None,
                       "moving_object_id_and_path": None, "native_raw_file": None, "cd_dat_file": None,
                       "trigger_file_and_clock_origin": None, "serial_transcript_file": None,
                       "done_report": None, "optical_trace_file": None, "timing_uncertainty_us": None,
                       "reference_colour_method": None, "quality_notes": None, "second_copy_verified": None}}
        (output / (run["id"] + "_metadata.json")).write_text(json.dumps(metadata, indent=2) + "\n")
        sheet.append([run["id"], run["layout"], run["motion"], command,
                      (str(planned_total / 1e6) + "+ (self-timed)") if legacy else
                      (planned_total / 1e6 if planned_total else "unresolved"), "unrecorded"])
    out = io.StringIO(newline="")
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(["run_id", "layout", "motion", "command", "planned_seconds", "status"])
    writer.writerows(sheet)
    (output / "run_sheet.csv").write_text(out.getvalue())
    print("Prepared 21 run records in", output)
    if selected is None:
        print("C/D/J/M2/M3 schedules unresolved: prepare a NEW bundle with --selected T1, T2 or T3 after screening.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("--check", action="store_true")
    prep = sub.add_parser("prepare")
    prep.add_argument("--output", type=Path, required=True)
    prep.add_argument("--selected", choices=["T1", "T2", "T3"])
    args = parser.parse_args()
    if args.command == "generate":
        generate(args.check)
    else:
        prepare(args.output, args.selected)


if __name__ == "__main__":
    main()
